#define RNG_HEALTH_FAIL_COUNT_OFFSET UINT32_C(0x030)
#define RNG_SOURCE_STATUS_OFFSET     UINT32_C(0x034)
#define RNG_IP_ID_OFFSET             UINT32_C(0x0F4)
#define RNG_IP_VERSION_OFFSET        UINT32_C(0x0F8)
#define RNG_CAPABILITY_OFFSET        UINT32_C(0x0FC)

#define RNG_CTRL_ENABLE_MASK         UINT32_C(0x00000001)
#define RNG_CTRL_FLUSH_MASK          UINT32_C(0x00000002)
#define RNG_CTRL_RECOVER_MASK        UINT32_C(0x00000004)
#define RNG_CTRL_VALID_MASK          UINT32_C(0x00000007)

